const { writeFileSync } = require('node:fs');
const { join } = require('node:path');

const HARDCOVER_API = 'https://api.hardcover.app/v1/graphql';

const query = `{
  me {
    user_books(where: {status_id: {_eq: 2}}, order_by: {id: asc}) {
      first_started_reading_date
      date_added
      updated_at
      created_at
      reading_journals(
        where: {event: {_in: ["status_currently_reading", "progress_updated"]}}
        order_by: {action_at: desc}
        limit: 1
      ) {
        action_at
      }
      book {
        title
        slug
        cached_contributors
      }
    }
  }
}`;

async function main() {
    const apiKey = process.env.HARDCOVER_API_KEY;
    if (!apiKey) {
        console.error('Error: HARDCOVER_API_KEY environment variable is required');
        process.exit(1);
    }

    const response = await fetch(HARDCOVER_API, {
        method: 'POST',
        headers: {
            'content-type': 'application/json',
            authorization: apiKey.startsWith('Bearer ') ? apiKey : `Bearer ${apiKey}`,
        },
        body: JSON.stringify({ query }),
        signal: AbortSignal.timeout(30_000),
    });

    if (!response.ok) {
        console.error(`API request failed: ${response.status} ${response.statusText}`);
        process.exit(1);
    }

    const { data, errors } = await response.json();

    if (errors?.length) {
        console.error('GraphQL errors:', JSON.stringify(errors, null, 2));
        process.exit(1);
    }

    const userBooks = data?.me?.[0]?.user_books;
    if (!Array.isArray(userBooks)) throw new Error('Hardcover returned no authenticated library');

    const latest = userBooks.map(entry => ({
        entry,
        updatedAt: Math.max(
            Date.parse(entry.updated_at || entry.created_at),
            Date.parse(entry.reading_journals[0]?.action_at || entry.created_at),
        ),
    })).sort((a, b) => b.updatedAt - a.updatedAt)[0];

    const lines = ['# Auto-generated by scripts/fetch-hardcover.js'];
    if (latest) {
        const { book, first_started_reading_date, date_added } = latest.entry;
        if (!book?.title || !book.slug) throw new Error('Hardcover returned a book without a title or slug');
        const author = book.cached_contributors?.[0]?.author?.name
            || book.cached_contributors?.[0]?.name
            || 'Unknown';

        lines.push('');
        lines.push(`- title: ${JSON.stringify(book.title)}`);
        lines.push(`  author: ${JSON.stringify(author)}`);
        lines.push(`  hardcover_url: ${JSON.stringify('https://hardcover.app/books/' + encodeURIComponent(book.slug))}`);
        if (first_started_reading_date || date_added) {
            lines.push(`  started_at: ${JSON.stringify(first_started_reading_date || date_added)}`);
        }
        lines.push(`  updated_at: ${JSON.stringify(new Date(latest.updatedAt).toISOString())}`);
    } else {
        lines.push('[]');
    }

    lines.push('');

    writeFileSync(join(__dirname, '..', 'data', 'activity', 'currently_reading.yaml'), lines.join('\n'));
}

main().catch(err => {
    console.error(err);
    process.exit(1);
});
